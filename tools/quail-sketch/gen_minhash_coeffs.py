#!/usr/bin/env python3
"""Writes crates/quail-sketch/src/coeffs.rs: the 128 MinHash permutations (a, b) as const tables.

They are exactly the ones a CPython service computes with
``random.Random(0x5ADAF19315).randrange(1, p)`` (128 values of a) then ``randrange(0, p)``
(128 values of b), p = 2^61 - 1, so `sketch.minhash_sada` signatures are byte-identical to it.
The native `sketch.minhash` reuses the same table. CPython's Mersenne Twister and randrange are
stable across versions for integer seeds, so re-running this script must give the same file.

Usage: python3 tools/quail-sketch/gen_minhash_coeffs.py > crates/quail-sketch/src/coeffs.rs
"""

import random

SEED = 0x5ADAF19315
P = (1 << 61) - 1
N = 128

rng = random.Random(SEED)
a = [rng.randrange(1, P) for _ in range(N)]
b = [rng.randrange(0, P) for _ in range(N)]


def table(name, doc, values):
    lines = [f"/// {doc}", f"pub(crate) const {name}: [u64; {N}] = ["]
    for v in values:
        lines.append(f"    0x{v:016x},")
    lines.append("];")
    return "\n".join(lines)


print("// @generated by tools/quail-sketch/gen_minhash_coeffs.py; do not edit by hand.")
print("// Python: random.Random(0x5ADAF19315): 128 x randrange(1, 2^61-1), then 128 x randrange(0, 2^61-1).")
print()
print(table("A", "Multipliers `a` of the 128 permutations `(a·x + b) mod (2^61 − 1)`.", a))
print()
print(table("B", "Offsets `b` of the 128 permutations `(a·x + b) mod (2^61 − 1)`.", b))
