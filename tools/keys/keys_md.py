"""Writes docs/keys.md, the reference of every step and fact key, from a built `quail` binary.

    python3 tools/keys/keys_md.py --quail target/debug/quail > docs/keys.md
    python3 tools/keys/keys_md.py --quail target/debug/quail --check docs/keys.md

The input is `quail keys --json` (every key with its doc, every step) and
`quail version --profile P --json` for each profile (the lowest profile a step runs in). The
output depends only on those, so it is the same on every machine. `--check FILE` exits 1 when
FILE differs from what would be written. `make keys` / `make keys-check` wrap both.
"""
import argparse
import json
import subprocess
import sys

PROFILES = ["fast", "standard", "deep"]

# Namespace -> heading text. A namespace missing here is listed under its own name.
TITLES = {
    "engine": "engine: format sniffing and dedup",
    "hash": "hash: identity of the bytes",
    "pdf": "pdf: PDF extractor",
    "docx": "docx: DOCX extractor",
    "text": "text: text statistics and language",
    "signal": "signal: identifiers, dates, amounts, contacts",
    "ref": "ref: document numbers, citations, titles",
    "party": "party: companies and roles",
    "clause": "clause: contract clauses",
    "item": "item: price lines",
    "sketch": "sketch: similarity sketches",
    "summary": "summary: file card and summaries",
    "ocr": "ocr: OCR",
}


def run(quail, *args):
    out = subprocess.run([quail, *args], check=True, capture_output=True, text=True)
    return json.loads(out.stdout)


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ")


def render(quail):
    keys = run(quail, "keys", "--json")
    lowest = {}
    features = []
    for p in PROFILES:
        v = run(quail, "version", "--profile", p, "--json")
        features = v["features"]
        for s in v["steps"]:
            lowest.setdefault(s["id"], p)

    out = []
    w = out.append
    w("# Fact keys")
    w("")
    w("<!-- Generated by tools/keys/keys_md.py from `quail keys --json`; do not edit.")
    w("     Regenerate with `make keys`. -->")
    w("")
    w("Every step and every fact key of the default `quail` build (features: "
      + ", ".join(f"`{f}`" for f in features) + "), with the documentation from the crate that")
    w("declares it. Value types and the fields of record values are named in each entry; the")
    w("value encoding is described in [concepts.md](concepts.md#3-values). `quail keys PREFIX`")
    w("prints the same list for your own build. A build with `--features ocr` adds the step")
    w("`ocr.pages@2` (profile `deep`) and the `ocr.*` keys (`ocr.pages`, `ocr.chars`, `ocr.mean_conf`,")
    w("`ocr.script`, `ocr.page`), documented in `crates/quail-ocr/README.md`.")
    w("")
    nss = []
    for k in keys["keys"]:
        ns = k["key"].split(".", 1)[0]
        if ns not in nss:
            nss.append(ns)
    w("Namespaces: " + " · ".join(f"[`{ns}`](#{ns})" for ns in nss))
    w("")
    w("## Steps")
    w("")
    w("In registration order. *Profile* is the lowest profile the step runs in (`dedup` only "
      "with `scan --dedup`).")
    w("")
    w("| step | kind | formats | profile | what it does |")
    w("|---|---|---|---|---|")
    for s in keys["steps"]:
        fmts = ", ".join(s["formats"]) if s["formats"] else "any"
        prof = lowest.get(s["id"], "-")
        w(f"| `{s['id']}` | {s['kind']} | {fmts} | {prof} | {cell(s['doc'])} |")
    w("")
    for ns in nss:
        group = [k for k in keys["keys"] if k["key"].split(".", 1)[0] == ns]
        crates = sorted({k["crate"] for k in group})
        w(f'<a id="{ns}"></a>')
        w("")
        w(f"## {TITLES.get(ns, ns)}")
        w("")
        w(f"Declared by {', '.join(f'`{c}`' for c in crates)}. {len(group)} keys.")
        w("")
        w("| key | documentation |")
        w("|---|---|")
        for k in group:
            w(f"| `{k['key']}` | {cell(k['doc'])} |")
        w("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--quail", default="target/debug/quail", help="path to the quail binary")
    ap.add_argument("--check", metavar="FILE", help="compare with FILE instead of printing")
    a = ap.parse_args()
    text = render(a.quail)
    if a.check:
        with open(a.check, encoding="utf-8") as f:
            if f.read() != text:
                print(f"{a.check} is out of date: run `make keys`", file=sys.stderr)
                sys.exit(1)
        return
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
