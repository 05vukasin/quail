//! MinHash signatures of word shingles and their LSH band keys.
//!
//! # Definition (stable; changing any of it needs a new `sketch.minhash` version)
//!
//! 1. Text: page texts joined by `'\n'`, normalized with `quail_text::normalize` defaults.
//! 2. Shingles: `quail_text::shingle::text_shingles(text, 3, &FoldOptions::KEY)`: word
//!    3-shingles of the folded tokens (case, diacritics and Serbian script do not matter),
//!    each an XXH3-64 hash pinned by `quail-text`. The *set* of shingles is used.
//! 3. 128 permutations `h_i(x) = (a_i·x + b_i) mod (2^61 − 1)` over the 64-bit shingle hash
//!    `x`, with the coefficient table generated by `tools/quail-sketch/gen_minhash_coeffs.py`
//!    (the same table as [`crate::compat`]). Row `i` is `min_x h_i(x)`.
//! 4. Stored row: the low 32 bits of the minimum, little-endian, 128 × 4 = 512 bytes. Two rows
//!    agree by accident with probability 2^-32, which does not move the estimate.
//! 5. LSH: 32 bands of 4 rows. Band key `j` is `quail_text::shingle::hash_bytes([j] ‖ the
//!    16 bytes of rows 4j..4j+4)`, so keys of different bands never meet.
//!
//! # Comparison
//!
//! [`crate::jaccard_estimate`] (share of equal rows) estimates the Jaccard index of the two
//! shingle sets, ±0.04 at 0.6. Two files share at least one band key with probability
//! `1 − (1 − J^4)^32`: 0.50 at J ≈ 0.385, 0.64 at 0.42, 0.87 at 0.5, 0.99 at 0.6, so the bands are a
//! permissive first stage and the estimate confirms:
//!
//! - near-duplicate: J ≥ [`NEAR_DUP_JACCARD`] (0.60);
//! - version of the same document (one edited copy of another): J ≥ [`VERSION_JACCARD`] (0.90);
//!   next month's invoice from one template lands near 0.6, a changed date in a two-page
//!   contract near 0.99. Between the two bars the pair needs other evidence (an identifier,
//!   a title, a page match).
//!
//! Bodies with fewer than [`MIN_SHINGLES`] distinct shingles (a cover sheet, a stub) get no
//! signature: too short to judge.

use quail_text::fold::FoldOptions;
use quail_text::shingle::{Shingles, hash_bytes, text_shingles};

use crate::coeffs::{A, B};

/// Rows of a signature.
pub const PERMUTATIONS: usize = 128;
/// LSH bands.
pub const BANDS: usize = 32;
/// Rows per band.
pub const ROWS: usize = 4;
/// Words per shingle.
pub const SHINGLE_WORDS: usize = 3;
/// Fewest distinct shingles for a signature to be emitted.
pub const MIN_SHINGLES: usize = 40;
/// Estimated Jaccard at or above which two files are near-duplicates.
pub const NEAR_DUP_JACCARD: f64 = 0.60;
/// Estimated Jaccard at or above which two files are versions of one document on the text
/// alone.
pub const VERSION_JACCARD: f64 = 0.90;

/// The Mersenne prime 2^61 − 1.
pub(crate) const P: u64 = (1 << 61) - 1;

/// `(a·x + b) mod p` exactly, for `a, b < p` and any 64-bit `x`.
#[inline]
#[allow(clippy::many_single_char_names)] // the textbook names
pub(crate) fn permute(a: u64, b: u64, x: u64) -> u64 {
    const M: u128 = P as u128;
    // v < 2^61·2^64 + 2^61 < 2^126; 2^61 ≡ 1 (mod p), so fold the high part down twice.
    let v = u128::from(a) * u128::from(x) + u128::from(b);
    let r = (v & M) + (v >> 61); // < 2^66
    let r = (r & M) + (r >> 61); // < 2^61 + 32
    #[allow(clippy::cast_possible_truncation)] // r < 2^62
    let mut r = r as u64;
    if r >= P {
        r -= P;
    }
    r
}

/// The 128 row minima of a set of 64-bit feature hashes (duplicates do not matter). All rows
/// are `u64::MAX` for an empty set.
pub fn signature_of(hashes: &[u64]) -> [u64; PERMUTATIONS] {
    let mut mins = [u64::MAX; PERMUTATIONS];
    for &x in hashes {
        for ((m, &a), &b) in mins.iter_mut().zip(&A).zip(&B) {
            let h = permute(a, b, x);
            if h < *m {
                *m = h;
            }
        }
    }
    mins
}

/// A MinHash signature as `sketch.minhash` stores it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct MinHash {
    /// Low 32 bits of each row minimum.
    pub rows: [u32; PERMUTATIONS],
    /// Distinct shingles it was computed from.
    pub shingles: usize,
}

impl MinHash {
    /// Signature of a set of shingle hashes; sorts and deduplicates `hashes` in place. `None`
    /// for an empty set.
    pub fn from_hashes(hashes: &mut Vec<u64>) -> Option<Self> {
        hashes.sort_unstable();
        hashes.dedup();
        if hashes.is_empty() {
            return None;
        }
        let full = signature_of(hashes);
        let mut rows = [0u32; PERMUTATIONS];
        for (r, f) in rows.iter_mut().zip(full) {
            #[allow(clippy::cast_possible_truncation)] // the low 32 bits, on purpose
            let low = f as u32;
            *r = low;
        }
        Some(Self {
            rows,
            shingles: hashes.len(),
        })
    }

    /// The stored form: 128 rows × 4 bytes little-endian.
    pub fn to_bytes(&self) -> Vec<u8> {
        self.rows.iter().flat_map(|r| r.to_le_bytes()).collect()
    }

    /// The 32 LSH band keys.
    pub fn bands(&self) -> [u64; BANDS] {
        let mut keys = [0u64; BANDS];
        let mut buf = [0u8; 1 + ROWS * 4];
        for (j, (key, band)) in keys
            .iter_mut()
            .zip(self.rows.chunks_exact(ROWS))
            .enumerate()
        {
            #[allow(clippy::cast_possible_truncation)] // j < 32
            let tag = j as u8;
            buf[0] = tag;
            for (dst, r) in buf[1..].chunks_exact_mut(4).zip(band) {
                dst.copy_from_slice(&r.to_le_bytes());
            }
            *key = hash_bytes(&buf);
        }
        keys
    }

    /// Estimated Jaccard index against another signature.
    pub fn jaccard(&self, other: &Self) -> f64 {
        let equal = self
            .rows
            .iter()
            .zip(&other.rows)
            .filter(|(a, b)| a == b)
            .count();
        #[allow(clippy::cast_precision_loss)] // at most 128
        let share = equal as f64 / PERMUTATIONS as f64;
        share
    }
}

/// Shingle hashes `sketch.minhash` uses for already-normalized `text` (step 2 of the
/// definition), appended to `out`.
pub fn shingle_hashes(text: &str, out: &mut Vec<u64>) {
    out.extend(text_shingles(text, SHINGLE_WORDS, &FoldOptions::KEY));
}

/// [`shingle_hashes`] from the token key hashes of the text (`hash_str` of each folded key,
/// in order) instead of the text.
pub(crate) fn shingle_hashes_of_keys(key_hashes: Vec<u64>, out: &mut Vec<u64>) {
    out.extend(Shingles::from_hashes(key_hashes.into_iter(), SHINGLE_WORDS));
}

/// MinHash of a text: normalizes it, shingles it and signs the set. `None` without any
/// token. The minimum-shingle gate ([`MIN_SHINGLES`]) is the caller's (the analyzer applies
/// it); check [`MinHash::shingles`].
pub fn text_minhash(text: &str) -> Option<MinHash> {
    let norm =
        quail_text::normalize::normalize(text, &quail_text::normalize::NormalizeOptions::default());
    let mut hashes = Vec::new();
    shingle_hashes(&norm, &mut hashes);
    MinHash::from_hashes(&mut hashes)
}

/// Probability that two files with Jaccard index `j` share at least one band key.
pub fn band_collision_probability(j: f64) -> f64 {
    #[allow(clippy::cast_possible_truncation, clippy::cast_possible_wrap)] // small constants
    let (rows, bands) = (ROWS as i32, BANDS as i32);
    1.0 - (1.0 - j.powi(rows)).powi(bands)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn permute_is_exact() {
        for &(a, b, x) in &[
            (1u64, 0u64, 0u64),
            (P - 1, P - 1, u64::MAX),
            (12345, 678, 1 << 63),
            (A[0], B[0], 0xdead_beef_cafe_babe),
        ] {
            let want = (u128::from(a) * u128::from(x) + u128::from(b)) % u128::from(P);
            assert_eq!(u128::from(permute(a, b, x)), want);
        }
    }

    #[test]
    fn collision_curve() {
        assert!((band_collision_probability(0.385) - 0.5).abs() < 0.02);
        assert!(band_collision_probability(0.6) > 0.98);
        assert!(band_collision_probability(0.1) < 0.01);
    }
}
