/// Decodes standard base64 (padding optional, whitespace ignored).
pub fn b64(s: &str) -> Vec<u8> {
    let val = |c: u8| match c {
        b'A'..=b'Z' => Some(c - b'A'),
        b'a'..=b'z' => Some(c - b'a' + 26),
        b'0'..=b'9' => Some(c - b'0' + 52),
        b'+' => Some(62),
        b'/' => Some(63),
        _ => None,
    };
    let (mut out, mut acc, mut n) = (Vec::new(), 0u32, 0u32);
    for v in s.bytes().filter_map(val) {
        acc = (acc << 6) | u32::from(v);
        n += 6;
        if n >= 8 {
            n -= 8;
            out.push((acc >> n) as u8);
        }
    }
    out
}

/// A reproducer's PDF bytes: base64, gunzipped when it is gzip.
pub fn pdf(s: &str) -> Vec<u8> {
    let raw = b64(s);
    if raw.starts_with(&[0x1f, 0x8b]) {
        let mut out = Vec::new();
        flate2::read::GzDecoder::new(raw.as_slice())
            .read_to_end(&mut out)
            .expect("gzip");
        out
    } else {
        raw
    }
}
