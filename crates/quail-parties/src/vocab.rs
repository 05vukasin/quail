/// Whether `key` is in `list`.
pub fn has(list: &[&str], key: &str) -> bool {
    list.contains(&key)
}

/// The value paired with `key` in `pairs`.
pub fn lookup(pairs: &[(&'static str, &'static str)], key: &str) -> Option<&'static str> {
    pairs.iter().find(|(k, _)| *k == key).map(|(_, v)| *v)
}

/// A legal-form word (`LEGAL_FORM_WORDS`).
pub fn is_legal_form_word(key: &str) -> bool {
    has(LEGAL_FORM_WORDS, key)
}

/// A noise word (`NOISE_WORDS` = legal forms + trade nouns + extras).
pub fn is_noise_word(key: &str) -> bool {
    is_legal_form_word(key) || has(TRADE_NOUNS, key) || has(NOISE_EXTRA, key)
}

/// A jurisdiction word (`GEO_TOKENS`).
pub fn is_geo(key: &str) -> bool {
    has(GEO_TOKENS, key)
}

/// A role term word (`ROLE_TERM_WORDS`).
pub fn is_role_term_word(key: &str) -> bool {
    has(ROLE_TERM_WORDS, key)
}
